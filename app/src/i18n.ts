export const lang = navigator.language.toLowerCase().startsWith("it") ? "it" : "en";
export const t: Strings = lang === "it" ? it : en;

export const num = (n: number, digits = 0) =>
  n.toLocaleString(lang, { minimumFractionDigits: digits, maximumFractionDigits: digits });

export function bytes(b: number) {
  const units = ["B", "KB", "MB", "GB"];
  let i = 0;
  while (b >= 1024 && i < units.length - 1) {
    b /= 1024;
    i++;
  }
  return `${num(b, i === 0 ? 0 : 1)} ${units[i]}`;
}
